"""Class relationships for the software map, read from the live package with pydoc's own tools.

``uv run python docs/tools/classmap.py`` rewrites docs/softmap.classes.toml; ``--check`` exits 1 if the
file is stale. It imports oaken_core, so it runs in the project environment, not the docs one: the
site build only reads the committed file. Each class is filed under the softmap component whose
``path`` is the longest prefix of its source file. Only classes that take part in an in-core
inheritance (a subclass of one, or a base of one) are recorded.
"""

import importlib
import inspect
import pkgutil
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "docs" / "softmap.classes.toml"
HEADER = "# Generated by docs/tools/classmap.py from the live package. Do not edit; rerun the tool.\n"


def collect() -> list[dict]:
    import oaken_core

    classes: dict[type, str] = {}
    for m in pkgutil.walk_packages(oaken_core.__path__, "oaken_core."):
        mod = importlib.import_module(m.name)
        for _, c in inspect.getmembers(mod, inspect.isclass):
            if c.__module__ == m.name:
                classes[c] = m.name
    parents = {b for c in classes for b in c.__bases__ if b in classes}
    paths = sorted((c["path"] for c in tomllib.loads((ROOT / "docs" / "softmap.toml").read_text())["components"] if c.get("path")), key=len, reverse=True)
    rows = []
    for c, modname in classes.items():
        if c not in parents and not any(b in classes for b in c.__bases__):
            continue
        src = str(Path(inspect.getsourcefile(c) or "").resolve().relative_to(ROOT))
        comp = next((p for p in paths if src == p or src.startswith(p + "/")), "")
        rows.append({"name": c.__name__, "module": modname, "path": comp, "bases": [b.__name__ for b in c.__bases__ if b is not object], "doc": inspect.cleandoc(c.__dict__.get("__doc__") or "").split("\n")[0]})
    return sorted(rows, key=lambda r: (r["module"], r["name"]))


def q(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def render(rows: list[dict]) -> str:
    out = [HEADER]
    for r in rows:
        out.append(f"[[classes]]\nname = {q(r['name'])}\nmodule = {q(r['module'])}\npath = {q(r['path'])}\nbases = [{', '.join(map(q, r['bases']))}]\ndoc = {q(r['doc'])}\n")
    return "\n".join(out)


if __name__ == "__main__":
    text = render(collect())
    if "--check" in sys.argv:
        sys.exit(0 if OUT.exists() and OUT.read_text() == text else 1)
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {text.count('[[classes]]')} classes")
